import { test, expect } from '@playwright/test';
test('fresh setup → project → hosted signup → PKCE callback → administrator logout', async ({ page, context }) => {
  const failures: string[] = [];
  page.on('pageerror', error => failures.push(error.message));
  await page.goto('/');
  await expect(page.getByRole('heading', { name: 'First-time setup' })).toBeVisible();
  await expect(page.getByText('Open the private setup link', { exact: false })).toBeVisible();
  await expect(page.locator('form')).toHaveCount(0);
  await page.goto('/setup#invalid-setup-link');
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible();
  await expect(page).toHaveURL('http://localhost:4200/setup');
  await page.getByLabel('Email', { exact: true }).fill('browser-admin@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('browser-admin-password');
  await page.getByRole('button', { name: 'Create administrator' }).click();
  await expect(page.getByRole('alert')).toHaveText('This setup link is invalid. Open the link printed by the setup command.');
  await page.goto('/setup#' + encodeURIComponent('browser-setup-token&with+symbols=#'));
  await expect(page.getByLabel('Email', { exact: true })).toBeVisible();
  await expect(page).toHaveURL('http://localhost:4200/setup');
  await expect(page.getByLabel('Setup token')).toHaveCount(0);
  expect(await page.evaluate(() => JSON.stringify([localStorage, sessionStorage]))).not.toContain('browser-setup-token');
  await page.getByLabel('Email', { exact: true }).fill('browser-admin@example.invalid');
  await page.getByLabel('Password', { exact: true }).fill('browser-admin-password');
  await page.getByRole('button', { name: 'Create administrator' }).click();
  await expect(page.getByRole('heading', { name: 'Your projects' })).toBeVisible();
  await page.getByRole('button', { name: 'Create project', exact: true }).click();
  await page.getByLabel('Project name').fill('Browser project');
  await page.getByRole('button', { name: 'Continue', exact: true }).click();
  await page.getByRole('button', { name: 'Review', exact: true }).click();
  await page.getByRole('button', { name: 'Save project' }).click();
  await expect(page.getByRole('heading', { name: 'Connect your application' })).toBeVisible();
  const [example] = await Promise.all([context.waitForEvent('page'), page.getByRole('link', { name: 'Try login in the example application' }).click()]);
  example.on('pageerror', error => failures.push(error.message));
  await example.getByRole('button', { name: 'Sign in', exact: true }).click();
  await expect(example.getByRole('heading', { name: 'Browser project' })).toBeVisible();
  await example.getByRole('button', { name: 'Create an account', exact: true }).click();
  await example.getByLabel('Email', { exact: true }).fill('browser-person@example.invalid');
  await example.getByLabel('Password', { exact: true }).fill('browser-person-password');
  const initialTokenPromise = example.waitForResponse(response => response.url().endsWith('/token') && response.request().method() === 'POST');
  await example.getByRole('button', { name: 'Create account', exact: true }).click();
  const initialToken = (await (await initialTokenPromise).json()).access_token;
  await expect(example.getByRole('status')).toHaveText('Signed in successfully');
  await expect(example.locator('#profile')).toContainText('browser-person@example.invalid');
  await expect(example).toHaveURL('http://localhost:4200/example/');
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Connect your application' })).toBeVisible();
  const settingsUrl = page.url();
  await page.getByRole('button', { name: 'Light', exact: true }).click();
  await expect(page.locator('html')).not.toHaveClass(/rouge-dark/);
  await page.getByRole('button', { name: 'Dark', exact: true }).click();
  await expect(page.locator('html')).toHaveClass(/rouge-dark/);
  await page.setViewportSize({ width: 375, height: 900 });
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Roles', exact: true })).toBeVisible();
  await expect(page.getByText('Default', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Users', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Users', exact: true })).toBeVisible();
  await expect(page.getByText('browser-person@example.invalid', { exact: true })).toBeVisible();
  const table = page.locator('.p-datatable-table-container');
  expect(await table.evaluate(element => getComputedStyle(element).overflowX)).toBe('auto');
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Permissions', exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Permissions', exact: true })).toBeVisible();
  await expect(page.getByText('No permissions configured yet.')).toBeVisible();
  // Manage permissions and roles, then assign access to the registered project user.
  await page.getByRole('button', { name: 'Create permission', exact: true }).click();
  await page.getByLabel('Permission key', { exact: true }).fill('articles:read');
  await page.getByRole('button', { name: 'Save permission', exact: true }).click();
  await expect(page.getByText('articles:read', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Roles', exact: true }).click();
  await page.getByRole('button', { name: 'Create role', exact: true }).click();
  await page.getByLabel('Role name', { exact: true }).fill('Editor');
  await page.getByLabel('articles:read', { exact: true }).check();
  await page.getByRole('button', { name: 'Save role', exact: true }).click();
  await expect(page.getByText('Editor', { exact: true })).toBeVisible();
  await page.getByRole('button', { name: 'Open navigation' }).click();
  await page.getByRole('button', { name: 'Users', exact: true }).click();
  await page.getByRole('combobox', { name: 'Role for browser-person@example.invalid' }).selectOption({ label: 'Editor' });
  await expect(page.getByRole('status')).toContainText('Role updated.');
  // The callback cleared its query; obtain the tenant code from the project's integration view.
  await page.goto(settingsUrl);
  const code = await page.locator('dt').filter({ hasText: /^Tenant code$/ }).locator('+ dd').innerText();
  const revoked = await context.request.get(`/api/auth/${code}/me`, { headers: { Authorization: `Bearer ${initialToken}` } });
  expect(revoked.status()).toBe(401);
  await example.goto(`/example/?tenant=${encodeURIComponent(code)}`);
  await example.getByRole('button', { name: 'Sign in', exact: true }).click();
  await example.getByLabel('Email', { exact: true }).fill('browser-person@example.invalid');
  await example.getByLabel('Password', { exact: true }).fill('browser-person-password');
  const updatedTokenPromise = example.waitForResponse(response => response.url().endsWith('/token') && response.request().method() === 'POST');
  await example.getByRole('button', { name: 'Sign in', exact: true }).click();
  const updatedToken = (await (await updatedTokenPromise).json()).access_token;
  const claims = JSON.parse(Buffer.from(updatedToken.split('.')[1], 'base64url').toString());
  expect(claims.roles).toEqual(['Editor']);
  expect(claims.permissions).toEqual(['articles:read']);
  await expect(example.getByRole('status')).toHaveText('Signed in successfully');
  await expect(example.locator('#profile')).toContainText('articles:read');
  await page.goto(settingsUrl);
  await page.setViewportSize({ width: 1280, height: 900 });
  await expect(page.getByRole('heading', { name: 'Connect your application' })).toBeVisible();
  await page.getByRole('button', { name: 'Account menu' }).click();
  await page.getByText('Logout', { exact: true }).click();
  await expect(page.getByRole('heading', { name: 'Administrator sign in' })).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading', { name: 'Administrator sign in' })).toBeVisible();
  await page.goto('/setup#' + encodeURIComponent('browser-setup-token&with+symbols=#'));
  await expect(page.getByRole('heading', { name: 'Administrator sign in' })).toBeVisible();
  await expect(page).toHaveURL('http://localhost:4200/auth/sign-in');
  expect(failures).toEqual([]);
});
